#ifndef SYLE_FIRMWARE_TIMER_IRQ_OWNER_H
#define SYLE_FIRMWARE_TIMER_IRQ_OWNER_H
#include <stdbool.h>
#include <stdint.h>
/* HOST-ONLY, independent opt-in state machine. Fixed vector32, unmasked
 * periodic initial10000000/div1; 100MHz bus, 10MHz reference. No configuration,
 * VMCS, IRQ delivery, guest APIC or receipt proof. Single serialized owner;
 * fresh zeroed storage, no copying/rollback/reinit/direct field mutation.
 * Pending is a coalesced edge, not an interrupt count. New sample-time expiry
 * during reservation remains pending after the older receipt is accounted.
 * No inference about exact delivery time between reference samples. */
struct fti_owner {
 uint64_t domain,origin,last,max_gap,deadline_bus;
 uint64_t expirations,generation,token,reserved_expirations;
 bool ready,pending,reserved,in_service,terminal;
};
#define FTI_VECTOR 32u
#define FTI_PERIOD_BUS UINT64_C(10000000)
bool fti_init(struct fti_owner*,uint64_t domain,uint64_t reference,uint64_t max_gap);
/* Monotonic clock/overflow failure terminal; pending/reservation preserved. */
bool fti_sample(struct fti_owner*,uint64_t domain,uint64_t reference);
/* Priority/IF/window admission is EXTERNAL. In-service blocks this vector.
 * No pending/reserved/in-service: false without mutation. Token exhaustion fatal. */
bool fti_reserve(struct fti_owner*,uint64_t *token,uint8_t *vector);
/* Caller must have verified and cleaned the exact VM-entry transaction.
 * These booleans are obligations, not receipt evidence generated by this API.
 * Invalid token/evidence permanently quarantines, never consumes pending. */
bool fti_cancel(struct fti_owner*,uint64_t token,bool cleaned_no_entry);
bool fti_account(struct fti_owner*,uint64_t token,bool cleaned_delivery_receipt);
/* Call only after committed guest EOI; empty EOI is an idempotent no-op.
 * No MMIO or VMCS commit is performed. Outstanding reservation rejects/fatal. */
bool fti_eoi(struct fti_owner*);
void fti_quarantine(struct fti_owner*);
#endif
